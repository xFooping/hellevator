// Regenerates js/names.js from tools/game-items.json.
// Usage: node tools/build-names.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const data = JSON.parse(readFileSync(join(root, "tools/game-items.json"), "utf8"));
const names = [...new Set([...data.items, ...data.legacy])].sort();
const js = `/* Every known Terraria item name (desktop 1.4.5 + old-gen/3DS exclusives).
   Used to tell "real thing, wrong prompt" apart from typos, and as the typo
   dictionary so suggestions never leak answers. Generated by tools/build-names.mjs. */
window.GAME_NAMES = ${JSON.stringify(names)};
`;
writeFileSync(join(root, "js/names.js"), js);
console.log(`wrote ${names.length} names`);
